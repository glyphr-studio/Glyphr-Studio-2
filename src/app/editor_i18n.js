export function getEditorLocale(locale = '') {
	const requested = locale || getGlassPreferences().language || 'en';
	return translations[requested] ? requested : 'en';
}

export function getEditorStrings(locale = '') {
	return translations[getEditorLocale(locale)];
}

export function editorText(key) {
	return getEditorStrings()[key] || en[key] || key;
}

export function applyEditorLanguage() {
	document.documentElement.lang = getEditorLocale();
}

